interface PhotoSeed {
  takenAt: string;
  city: string;
  locationName?: string;
  latitude?: number;
  longitude?: number;
  category: PhotoCategory;
  tags: string[];
  favorite?: boolean;
}

function buildPhotos(trip: Trip, seeds: PhotoSeed[]): Photo[] {
  return seeds.map((seed, i) => {
    const imgSeed = `${trip.id}-${String(i + 1).padStart(2, "0")}`;
    return {
      id: `photo-${imgSeed}`,
      tripId: trip.id,
      imageUrl: `https://picsum.photos/seed/${imgSeed}/800/600`,
      thumbnailUrl: `https://picsum.photos/seed/${imgSeed}/400/300`,
      takenAt: seed.takenAt,
      latitude: seed.latitude,
      longitude: seed.longitude,
      country: trip.country,
      city: seed.city,
      locationName: seed.locationName,
      aiTags: seed.tags,
      category: seed.category,
      isFavorite: seed.favorite ?? false,
      createdAt: `${trip.endDate}T20:00:00+09:00`,
    };
  });
}

